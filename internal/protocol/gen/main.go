// Command gen writes the TypeScript discriminated unions for every
// registered message type. Run via `make gen`.
package main

import (
	"flag"
	"fmt"
	"log"
	"os"
	"reflect"
	"strings"

	"github.com/kevinw93/QBuzzer/internal/protocol"
)

func main() {
	out := flag.String("out", "web/src/messages.ts", "output file")
	flag.Parse()

	var b strings.Builder
	b.WriteString("// Code generated by internal/protocol/gen. DO NOT EDIT.\n\n")
	b.WriteString("import type * as p from './protocol'\n\n")
	writeUnion(&b, "ClientMessage", protocol.ClientSpecs())
	writeUnion(&b, "ServerMessage", protocol.ServerSpecs())
	b.WriteString("export type ClientMessageType = ClientMessage['type']\n")
	b.WriteString("export type ServerMessageType = ServerMessage['type']\n\n")
	b.WriteString("export type PayloadOf<M extends { type: string; payload: unknown }, T extends M['type']> =\n")
	b.WriteString("  Extract<M, { type: T }>['payload']\n")

	if err := os.WriteFile(*out, []byte(b.String()), 0o644); err != nil { //nolint:gosec // generated source, world-readable is intended
		log.Fatal(err)
	}
}

func writeUnion(b *strings.Builder, name string, specs []protocol.Spec) {
	fmt.Fprintf(b, "export type %s =\n", name)
	for _, s := range specs {
		seq := ""
		if s.Seq {
			seq = " seq: number;"
		}
		fmt.Fprintf(b, "  | { type: '%s';%s payload: p.%s }\n", s.Type, seq, reflect.TypeOf(s.Payload).Name())
	}
	b.WriteString("\n")
}
