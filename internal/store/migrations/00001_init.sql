-- +goose Up

CREATE TABLE tournaments (
    id         bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    name       text        NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);

-- One row per room. The event log below is the source of truth; every other
-- game table is a projection rebuilt from the game's state.
CREATE TABLE games (
    id                      text PRIMARY KEY, -- generated by the server, so writes need no round trip
    tournament_id           bigint REFERENCES tournaments (id),
    code                    text        NOT NULL,
    epoch                   text        NOT NULL,
    moderator_password_hash text        NOT NULL, -- argon2id, PHC format
    rules                   jsonb       NOT NULL,
    created_at              timestamptz NOT NULL,
    last_active_at          timestamptz NOT NULL,
    finished_at             timestamptz
);

-- A code belongs to at most one unfinished game.
CREATE UNIQUE INDEX games_live_code ON games (code) WHERE finished_at IS NULL;

-- Append-only game log. seq is contiguous per game from 1; a gap means writes
-- were lost and the game can't be recovered.
CREATE TABLE game_events (
    game_id text        NOT NULL REFERENCES games (id) ON DELETE CASCADE,
    seq     integer     NOT NULL,
    kind    text        NOT NULL,
    at      timestamptz NOT NULL,
    data    jsonb       NOT NULL,
    PRIMARY KEY (game_id, seq)
);

-- Seats (sessions). token_hash is SHA-256 of the session token; the token
-- itself is never stored.
CREATE TABLE players (
    game_id    text    NOT NULL REFERENCES games (id) ON DELETE CASCADE,
    player_id  text    NOT NULL,
    role       text    NOT NULL,
    name       text    NOT NULL,
    token_hash text,
    last_seq   bigint  NOT NULL DEFAULT 0,
    team_id    text,
    PRIMARY KEY (game_id, player_id)
);

-- Projections, replaced as a set whenever the game's history or roster changes.
CREATE TABLE teams (
    game_id text NOT NULL REFERENCES games (id) ON DELETE CASCADE,
    team_id text NOT NULL,
    name    text NOT NULL,
    PRIMARY KEY (game_id, team_id)
);

CREATE TABLE tossups (
    game_id   text    NOT NULL REFERENCES games (id) ON DELETE CASCADE,
    number    integer NOT NULL,
    tossup_id text    NOT NULL,
    PRIMARY KEY (game_id, number)
);

-- One row per buzz. Times are milliseconds after the tossup started:
-- arrived_ms is when the server received it, judged_ms the clock-corrected
-- press time it was adjudicated by.
CREATE TABLE buzzes (
    game_id       text             NOT NULL,
    tossup_number integer          NOT NULL,
    buzz_id       text             NOT NULL,
    player_id     text             NOT NULL,
    team_id       text             NOT NULL,
    arrived_ms    double precision NOT NULL,
    judged_ms     double precision NOT NULL,
    rtt_ms        double precision, -- the connection's RTT estimate; null if none yet
    clamped       boolean          NOT NULL,
    status        text             NOT NULL,
    PRIMARY KEY (game_id, tossup_number, buzz_id),
    FOREIGN KEY (game_id, tossup_number) REFERENCES tossups (game_id, number) ON DELETE CASCADE
);

-- The moderator's verdict on a buzz.
CREATE TABLE rulings (
    game_id       text    NOT NULL,
    tossup_number integer NOT NULL,
    buzz_id       text    NOT NULL,
    result        text    NOT NULL, -- power, correct, neg, no_penalty
    points        integer NOT NULL,
    PRIMARY KEY (game_id, tossup_number, buzz_id),
    FOREIGN KEY (game_id, tossup_number, buzz_id) REFERENCES buzzes (game_id, tossup_number, buzz_id) ON DELETE CASCADE
);

CREATE TABLE bonus_parts (
    game_id          text    NOT NULL,
    tossup_number    integer NOT NULL,
    part             integer NOT NULL,
    team_id          text    NOT NULL, -- the team that earned the bonus
    correct          boolean NOT NULL,
    bounceback_team  text,
    points           integer NOT NULL,
    PRIMARY KEY (game_id, tossup_number, part),
    FOREIGN KEY (game_id, tossup_number) REFERENCES tossups (game_id, number) ON DELETE CASCADE
);

CREATE TABLE protests (
    game_id   text    NOT NULL REFERENCES games (id) ON DELETE CASCADE,
    ordinal   integer NOT NULL,
    tossup_id text    NOT NULL,
    filed_by  text    NOT NULL,
    note      text    NOT NULL,
    PRIMARY KEY (game_id, ordinal)
);

